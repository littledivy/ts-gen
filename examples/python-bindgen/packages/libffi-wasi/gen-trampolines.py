"""Writes trampolines.c: libffi-wasi's calls and closures for wasm32.

A Wasm function is called through the table with call_indirect, whose type
is fixed in the code, so a call or a callback whose signature is only known
at run time needs a function compiled for that signature. Each signature is
a return class and argument classes, after ffi.c lowers libffi types to the
four Wasm value types: i (i32: ints up to 32 bits, pointers, and structs
passed by address), j (i64), f (f32), d (f64), and v (a void return).

    python3 gen-trampolines.py > trampolines.c

Calls: every signature of up to CALL_ALL arguments, of up to CALL_ID
arguments of i and d only (C APIs' common case) for v, i and d returns,
and of up to CALL_I arguments of i only for v and i returns. Closures: the
same with CLOSURE_ALL, CLOSURE_ID and CLOSURE_I, CLOSURE_SLOTS callbacks
alive at once for each. Each closure entry point only passes its slot to
the signature's one function that packs the arguments, so a slot costs a
few bytes of code.
"""

import itertools

CALL_ALL = 3
CALL_ID = 6
CALL_I = 12
CLOSURE_ALL = 2
CLOSURE_ID = 4
CLOSURE_I = 6
CLOSURE_SLOTS = 4

C_TYPE = {"i": "int32_t", "j": "int64_t", "f": "float", "d": "double", "v": "void"}


def sigs(n, classes, rets):
    for k in range(n + 1):
        for args in itertools.product(classes, repeat=k):
            for r in rets:
                yield r + "_" + "".join(args)


def call_sigs():
    out = set(sigs(CALL_ALL, "ijfd", "vijfd"))
    out |= set(sigs(CALL_ID, "id", "vid"))
    out |= {r + "_" + "i" * k for k in range(CALL_I + 1) for r in "vi"}
    return sorted(out)


def closure_sigs():
    out = set(sigs(CLOSURE_ALL, "ijfd", "vijfd"))
    out |= set(sigs(CLOSURE_ID, "id", "vid"))
    out |= {r + "_" + "i" * k for k in range(CLOSURE_I + 1) for r in "vi"}
    return sorted(out)


def main():
    p = print
    p("/* Generated by gen-trampolines.py; see there. */")
    p("#include <stdint.h>")
    p('#include "trampolines.h"')
    p()
    calls = call_sigs()
    for s in calls:
        r, args = s.split("_")
        proto = ", ".join(C_TYPE[a] for a in args) or "void"
        call = ", ".join(f"*({C_TYPE[a]} *)&a[{i}]" for i, a in enumerate(args))
        fn = f"(({C_TYPE[r]} (*)({proto}))fn)({call})"
        body = fn + ";" if r == "v" else f"*({C_TYPE[r]} *)ret = {fn};"
        p(f"static void c_{s}(void (*fn)(void), uint64_t *a, void *ret) {{ (void)a; (void)ret; {body} }}")
    p()
    p(f"const ffi_wasi_call ffi_wasi_calls[{len(calls)}] = {{")
    for s in calls:
        p(f'  {{"{s}", c_{s}}},')
    p("};")
    p(f"const unsigned ffi_wasi_ncalls = {len(calls)};")
    p()
    closures = closure_sigs()
    for s in closures:
        r, args = s.split("_")
        p(f"static ffi_wasi_slot s_{s}[{CLOSURE_SLOTS}];")
        params = "".join(f", {C_TYPE[a]} x{i}" for i, a in enumerate(args))
        names = "".join(f", x{i}" for i in range(len(args)))
        stores = " ".join(f"*({C_TYPE[a]} *)&a[{i}] = x{i};" for i, a in enumerate(args))
        ret = "" if r == "v" else "return "
        p(f"static __attribute__((noinline)) {C_TYPE[r]} d_{s}(ffi_wasi_slot *s{params}) {{")
        p(f"  uint64_t a[{max(len(args), 1)}] = {{0}}, ret = 0; {stores}")
        p("  ffi_wasi_dispatch(s, a, &ret);")
        if r != "v":
            p(f"  return *({C_TYPE[r]} *)&ret;")
        p("}")
        for k in range(CLOSURE_SLOTS):
            p(f"static {C_TYPE[r]} e_{s}_{k}({params[2:] or 'void'}) {{ {ret}d_{s}(&s_{s}[{k}]{names}); }}")
        entries = ", ".join(f"(void (*)(void))e_{s}_{k}" for k in range(CLOSURE_SLOTS))
        p(f"static void (*const f_{s}[{CLOSURE_SLOTS}])(void) = {{{entries}}};")
    p()
    p(f"const ffi_wasi_closure_sig ffi_wasi_closure_sigs[{len(closures)}] = {{")
    for s in closures:
        p(f'  {{"{s}", s_{s}, f_{s}}},')
    p("};")
    p(f"const unsigned ffi_wasi_nclosure_sigs = {len(closures)};")
    p(f"const unsigned ffi_wasi_closure_slots = {CLOSURE_SLOTS};")


main()
